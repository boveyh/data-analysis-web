let current = 'zh';

export function setLang(lang) { current = lang === 'en' ? 'en' : 'zh'; }
export function getLang() { return current; }

/** Translate a key with optional {placeholder} interpolation. */
export function t(key, vars) {
  const table = STRINGS[current] || STRINGS.zh;
  let s = table[key];
  if (s === undefined) s = STRINGS.zh[key] !== undefined ? STRINGS.zh[key] : key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? vars[k] : m));
  return s;
}

/** The other language's strings — handy for comparing coverage in dev. */
export function other() { return current === 'zh' ? STRINGS.en : STRINGS.zh; }

/** Apply translations to every element carrying a data-i18n* attribute. */
export function applyStatic(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle); });
}
